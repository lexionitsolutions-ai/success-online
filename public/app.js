function bindWizard() {
  if (draft.step !== 2) return;
  const serviceSelect = document.querySelector('#service');
  const collectFields = () => document.querySelectorAll('#serviceFields [data-field]').forEach(input => { draft.details[decodeURIComponent(input.dataset.field)] = input.value; });
  const update = () => {
    const service = services.find(item => item.id === serviceSelect.value);
    if (!service) {
      document.querySelector('#requestVariant')?.remove();
      draft.serviceId = '';
      draft.variantId = '';
      document.querySelector('#serviceFields').innerHTML = '';
      document.querySelector('#svcInfo').innerHTML = '';
      document.querySelector('#serviceTimeline').innerHTML = '';
      return;
    }
    document.querySelector('#serviceTimeline').innerHTML=serviceTimeline(service);
    const variant = (service.slug==='gazette' && draft.details['Do you have any evidence of the new name?'] ? service.variants.find(item=>item.name===(draft.details['Do you have any evidence of the new name?']==='No'?'With affidavit charges':'Without affidavit charges')) : null) || service.variants.find(item => item.id === draft.variantId) || service.variants[0];
    const selector=document.querySelector('#requestVariant');
    if(selector) selector.remove();
    if(service.variants.length>1 && service.slug!=='gazette') {
      serviceSelect.closest('label').insertAdjacentHTML('afterend',`<label id="requestVariant">Request type<select>${service.variants.map(v=>`<option value="${h(v.id)}" ${v.id===variant.id?'selected':''}>${h(v.name)}</option>`).join('')}</select></label>`);
      document.querySelector('#requestVariant select').onchange=event=>{collectFields();draft.variantId=event.target.value;const selected=service.variants.find(v=>v.id===draft.variantId);for(const f of selected.fields.filter(f=>f.options?.length===1))draft.details[f.label]=f.options[0];update();};
    }
    for(const f of variant.fields.filter(f=>f.options?.length===1)) draft.details[f.label]=f.options[0];
    draft.serviceId = service.id;
    draft.variantId = variant.id;
    for (const field of variant.fields || []) {
      if (field.defaultWhen && draft.details[field.defaultWhen.field] === field.defaultWhen.equals) draft.details[field.label] = field.defaultWhen.value;
    }
    IntakeRules.applyComputed(variant.fields || [], draft.details);
    const visibleFields = (variant.fields || []).filter(field => IntakeRules.matches(field.when, draft.details) || (field.defaultWhen && draft.details[field.defaultWhen.field] === field.defaultWhen.equals));
    document.querySelector('#serviceFields').innerHTML = visibleFields.map((field, index) => {
      const key = encodeURIComponent(field.label);
      const rawValue = draft.details[field.label] || '';
      const value = h(rawValue);
      const automatic = field.computedSum || (field.defaultWhen && draft.details[field.defaultWhen.field] === field.defaultWhen.equals);
      const control = automatic ? `<input data-field="${key}" value="${value}" readonly aria-readonly="true">` : field.type === 'select'
        ? `<select data-field="${key}" ${field.optional ? 'data-optional="true"' : ''}><option value="" disabled hidden ${!rawValue ? 'selected' : ''}>Choose…</option>${(field.options || []).map(option => `<option value="${h(option)}" ${option === rawValue ? 'selected' : ''}>${field.label === 'Ration card colour' ? ({ Yellow: '\u{1F7E1} ', Orange: '\u{1F7E0} ', White: '\u26AA ' }[option] || '') : ''}${h(field.label === 'Ration card colour' ? ({ Yellow: 'Yellow (PHH)', Orange: 'Orange (PHH/NPH)', White: 'White (APL)' }[option] || option) : (field.optionLabels?.[option] || option))}</option>`).join('')}</select>`
        : field.type === 'textarea' ? `<textarea data-field="${key}" ${field.required ? 'required' : ''} placeholder="${h(field.placeholder || '')}" maxlength="500" rows="3">${value}</textarea>`
        : `<input data-field="${key}" type="${['email','date','number','tel','password'].includes(field.type) ? field.type : 'text'}" value="${value}" ${field.required ? 'required' : ''} ${field.allowNumbers ? 'data-allow-numbers="true"' : ''} ${field.min !== undefined ? `min="${h(field.min)}"` : ''} ${field.step ? `step="${h(field.step)}"` : ''} ${field.inputMode ? `inputmode="${h(field.inputMode)}"` : ''} ${field.placeholder ? `placeholder="${h(field.placeholder)}"` : ''} ${field.pattern ? `pattern="${h(field.pattern)}"` : ''} maxlength="${field.maxLength || 500}" ${field.sensitive ? 'autocomplete="off" data-sensitive="true"' : ''} ${field.digitsOnly ? 'oninput="this.value=this.value.replace(/[^0-9]/g,\'\').slice(0,' + (field.maxLength || 10) + ')"' : !field.allowNumbers && /\bname\b|\bsurname\b/i.test(field.label) ? 'oninput="removeNameNumbers(this)"' : ''}>`;
      const incomeYear = service.slug === 'income-certificate' && (field.label === 'Years of Certificate Required' || field.when?.field === 'Years of Certificate Required');
      const sectionStart = field.section && visibleFields[index - 1]?.section !== field.section;
      const sectionEnd = field.section && visibleFields[index + 1]?.section !== field.section;
      return `${sectionStart ? `<fieldset class="intake-field-section"><legend>${h(field.section)}</legend><p>${h(field.sectionNote || '')}</p><div class="formgrid">` : ''}<label${incomeYear ? ' class="income-year-field"' : field.fullWidth ? ' class="full-width-field"' : ''}>${h(field.displayLabel || field.label)}${field.marathiInput ? control.replace('<input ', '<input data-marathi-input lang="mr" spellcheck="false" autocomplete="off" ') + '<small class="marathi-preview" aria-live="polite"></small>' : control}${field.note ? `<small class="intake-field-note">${h(field.note)}</small>` : ''}</label>${sectionEnd ? '</div></fieldset>' : ''}`;
    }).join('');
    document.querySelector('#serviceFields').querySelectorAll('[data-field]').forEach(input => input.onchange = () => {
      const label = decodeURIComponent(input.dataset.field);
      const definition = variant.fields.find(field => field.label === label);
      if (!IntakeRules.matches(definition.when, draft.details)) return;
      draft.details[label] = input.value;
      collectFields();
      for (const field of variant.fields) {
        if (!IntakeRules.matches(field.when, draft.details)) delete draft.details[field.label];
      }
      if (service.slug==='gazette' && label==='Do you have any evidence of the new name?' || variant.fields.some(field => conditionUsesField(field.when, label) || conditionUsesField(field.defaultWhen, label))) update();
      else document.querySelector('#svcInfo').innerHTML = serviceGuidance(service, variant, draft.details);
    });
    document.querySelector('#svcInfo').innerHTML = serviceGuidance(service, variant, draft.details);
    for (const input of document.querySelectorAll('#serviceFields [data-field]')) input.addEventListener('input', () => {
      collectFields();
      IntakeRules.applyComputed(variant.fields || [], draft.details);
      for (const output of document.querySelectorAll('#serviceFields [data-field]')) {
        const label = decodeURIComponent(output.dataset.field);
        if (variant.fields.some(field => field.label === label && field.computedSum)) output.value = draft.details[label];
      }
    });
    if (draft.validationStep === 2) validateWizardFields(document.querySelectorAll('#serviceFields [data-field]'), false);
  };
  serviceSelect.onchange = () => { collectFields(); draft.details = {}; draft.variantId = ''; delete draft.validationStep; update(); };
  update();
}

function applicableDocuments(documents, details) {
  return documents.filter(item => IntakeRules.matches(item.when, details, true));
}

function conditionUsesField(condition, label) {
  return Boolean(condition && (condition.field === label || (condition.all || condition.any || []).some(rule => conditionUsesField(rule, label))));
}

