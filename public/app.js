function fieldWarning(input) {
  const label = input.dataset.field ? decodeURIComponent(input.dataset.field) : ({ name: 'Full name', mobile: 'Mobile number', service: 'a service' }[input.id] || input.name || 'this field');
  const value = input.value.trim();
  if (input.dataset.marathiInput !== undefined && value && !IntakeRules.isMarathiName(value)) return 'Please enter this name in Marathi.';
  const required = input.required || (input.tagName === 'SELECT' && input.dataset.optional !== 'true') || ['name', 'mobile'].includes(input.id);
  if (required && !value) return `${input.tagName === 'SELECT' ? 'Please choose' : 'Please enter'} ${label}.`;
  if (input.id === 'mobile' && !/^[6-9]\d{9}$/.test(value)) return 'Enter a valid 10-digit Indian mobile number.';
  if (!input.dataset.allowNumbers && (input.id === 'name' || /\bname\b|\bsurname\b/i.test(input.dataset.field ? decodeURIComponent(input.dataset.field) : '')) && /\p{N}/u.test(value)) return 'Name cannot contain numbers.';
  if (!input.checkValidity()) return input.validationMessage || `Check ${label}.`;
  return '';
}
function showFieldWarning(input) {
  const message = fieldWarning(input);
  const label = input.closest('label');
  const errorId = `field-error-${input.id || input.dataset.field}`;
  let warning = label?.querySelector('.field-warning');
  input.classList.toggle('field-invalid', Boolean(message));
  if (message) {
    input.setAttribute('aria-invalid', 'true');
    input.setAttribute('aria-describedby', errorId);
    if (!warning && label) {
      warning = document.createElement('small');
      warning.className = 'field-warning';
      warning.id = errorId;
      warning.setAttribute('role', 'alert');
      label.append(warning);
    }
    if (warning) warning.textContent = message;
  } else {
    input.removeAttribute('aria-invalid');
    input.removeAttribute('aria-describedby');
    warning?.remove();
  }
  return !message;
}
