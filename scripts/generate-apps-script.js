import { writeFileSync } from 'node:fs';
import { sheetHeaders } from '../operations-schema.js';
const script = `// Generated by npm run build. Paste this entire file into Google Apps Script.
const SHEET_HEADERS = ${JSON.stringify(sheetHeaders, null, 2)};

function setupSuccessOnlineWorkbook() {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  Object.keys(SHEET_HEADERS).forEach(function(name) {
    const headers = SHEET_HEADERS[name];
    const sheet = ss.getSheetByName(name) || ss.insertSheet(name);
    if (sheet.getMaxColumns() < headers.length) sheet.insertColumnsAfter(sheet.getMaxColumns(), headers.length - sheet.getMaxColumns());
    sheet.getRange(1, 1, 1, headers.length).setValues([headers]).setFontWeight('bold').setBackground('#0c2340').setFontColor('#ffffff');
    sheet.setFrozenRows(1);
    const filter = sheet.getFilter();
    if (filter) filter.remove();
    sheet.getRange(1, 1, Math.max(2, sheet.getLastRow()), headers.length).createFilter();
    sheet.autoResizeColumns(1, headers.length);
  });
  SpreadsheetApp.flush();
}

function rebuildDailyReport() {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  setupSuccessOnlineWorkbook();
  const cases = ss.getSheetByName('All Cases').getDataRange().getValues().slice(1);
  const payments = ss.getSheetByName('Cashflow').getDataRange().getValues().slice(1);
  const zone = ss.getSpreadsheetTimeZone();
  const today = Utilities.formatDate(new Date(), zone, 'yyyy-MM-dd');
  const rows = {};
  function day(value) {
    if (!value) return '';
    const date = new Date(value);
    return isNaN(date.getTime()) ? '' : Utilities.formatDate(date, zone, 'yyyy-MM-dd');
  }
  function bucket(key) { return rows[key] || (rows[key] = [key, 0, 0, 0, 0, 0, 0]); }
  cases.forEach(function(c) {
    if (!c[0]) return;
    const created = day(c[4]);
    if (created) bucket(created)[1]++;
    const completed = day(c[12]);
    if (completed && ['Closed','Delivered'].indexOf(c[9]) >= 0) bucket(completed)[4]++;
    if (['Closed','Delivered','Cancelled'].indexOf(c[9]) < 0) {
      bucket(today)[5]++;
      if (day(c[11]) && day(c[11]) < today) bucket(today)[6]++;
    }
  });
  payments.forEach(function(p) {
    const key = day(p[0]);
    if (key && p[2] !== 'demo' && ['PAID','verified','offline_approved'].indexOf(p[8]) >= 0) { bucket(key)[2]++; bucket(key)[3] += Number(p[7]) || 0; }
  });
  const daily = ss.getSheetByName('Daily Report');
  if (daily.getLastRow() > 1) daily.getRange(2, 1, daily.getLastRow() - 1, 7).clearContent();
  const values = Object.keys(rows).sort().map(function(key) { return rows[key]; });
  if (values.length) daily.getRange(2, 1, values.length, 7).setValues(values);
}

function safeCell(value) {
  const text = String(value == null ? '' : value);
  return /^[=+\\-@]/.test(text) ? "'" + text : text;
}
`;
writeFileSync('google-apps-script/Code.gs', script);
writeFileSync('google-apps-script/script.js', script);
