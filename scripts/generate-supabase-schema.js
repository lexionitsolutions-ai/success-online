import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const source = readFileSync('server.js','utf8');
const schema = source.match(/async function migrate\(\) \{\s*await db.exec\(`([\s\S]*?)`/)[1].replace(/\s*PRAGMA journal_mode = WAL;/,'').replace(/[ \t]+$/gm,'');
const tables = [...schema.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)/g)].map(match => match[1]);
mkdirSync('supabase',{recursive:true});
const indexes = `
CREATE INDEX IF NOT EXISTS cases_sales_idx ON cases(sales_user_id,created_at);
CREATE INDEX IF NOT EXISTS cases_backoffice_idx ON cases(backoffice_user_id,status);
CREATE INDEX IF NOT EXISTS documents_case_idx ON documents(case_id,doc_type,state);
CREATE INDEX IF NOT EXISTS notes_case_idx ON notes(case_id,created_at);
CREATE INDEX IF NOT EXISTS payments_case_idx ON payments(case_id,status);
CREATE INDEX IF NOT EXISTS uploads_case_idx ON upload_intents(case_id,completed_at,expires_at);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_idx ON users(LOWER(username));
`;
writeFileSync('supabase/schema.sql', '-- Generated by scripts/generate-supabase-schema.js. Run via npm run setup:supabase.\n' + schema + indexes + tables.map(table => `ALTER TABLE public.${table} ENABLE ROW LEVEL SECURITY;\nREVOKE ALL ON TABLE public.${table} FROM anon, authenticated;`).join('\n') + '\n');
