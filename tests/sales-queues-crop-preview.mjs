import {chromium} from 'playwright';
import {readFileSync,existsSync,mkdirSync} from 'node:fs';
import assert from 'node:assert/strict';
const executablePath=['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
const browser=await chromium.launch({headless:true,...(executablePath?{executablePath}:{})});
try {
  const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.setContent('<main id="app"></main>');
  for(const file of ['styles.css','mobile.css','dashboard.css','workspace.css']) await page.addStyleTag({content:readFileSync('public/'+file,'utf8')});
  await page.addScriptTag({content:readFileSync('public/intake-rules.js','utf8')});
  await page.addScriptTag({content:readFileSync('public/app.js','utf8').replace(/boot\(\);\s*$/,'')+`
    me={id:'sales',role:'sales',name:'Sales Staff',username:'sales'};
    const fixture=(id,status,payment='paid',documents='complete')=>({id,ref:id,priority:'Normal',status,payment_state:payment,document_state:documents,customer:{name:'Test Client',mobile:'9876543210'},service:{id:'service',name:'Certificate'},variant:{name:'Application'},amounts:{total:10000},updated_at:new Date().toISOString(),sales:{id:'sales',username:'sales'},backoffice:{name:'Office Staff'}});
    cases=[fixture('correct','Correction Required'),fixture('unpaid','Assigned','unpaid'),fixture('both','Awaiting Documents','unpaid','missing'),fixture('active','Assigned'),fixture('cash-balance','Closed')];
    cases[4].cashPayment={releaseAllowed:false,processingAllowed:true};
    caseNotifications=[{caseId:'correct'},{caseId:'both'}];
    window.testView=next=>{view=next;render();};
    window.testCrop=()=>{draft={docs:{}};document.querySelector('#app').innerHTML=uploadControls('Photo');};
    window.cropSaved=()=>draft.docs.Photo;
    window.testWorkflow=status=>{me={id:'office',role:'backoffice'};const item={...cases[0],status,backoffice:{id:'office'}};document.querySelector('#app').innerHTML=progressControls(item);applyIntakeLanguage();};
    window.testForwarding=()=>{me={role:'sales'};document.querySelector('#app').innerHTML=reuploadSubmissionPanel({id:'correct',reupload:{pending:true,canSubmit:true,pendingDocumentIds:['new'],missingTypes:[]}});applyIntakeLanguage();};
    rerenderWizard=()=>{};toast=()=>{};
  `});
  await page.evaluate(()=>testView('pendingDocuments'));
  assert.equal(await page.locator('.side [data-view="pending"]').count(),0);
  assert.equal(await page.locator('.case-table tbody tr').count(),2);
  assert.match(await page.locator('thead').innerText(),/Working Person/i);
  assert.doesNotMatch(await page.locator('thead').innerText(),/Salesperson|Owner/i);
  await page.evaluate(()=>testView('pendingPayment'));
  assert.equal(await page.locator('.case-table tbody tr').count(),3);
  await page.evaluate(()=>testView('cases'));
  assert.equal(await page.locator('.case-table tbody tr').count(),1);
  await page.evaluate(()=>testCrop());
  const png=await page.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=400;canvas.height=300;const ctx=canvas.getContext('2d');ctx.fillStyle='#f5e6c8';ctx.fillRect(0,0,400,300);ctx.fillStyle='#223c35';ctx.fillRect(80,60,240,180);return canvas.toDataURL('image/png').split(',')[1];});
  const upload=()=>page.locator('input[type=file]').first().setInputFiles({name:'scan.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
  await upload();
  await page.locator('.document-crop-dialog').waitFor();
  await page.locator('[data-crop-edge="0"]').fill('200');await page.locator('[data-crop-edge="0"]').dispatchEvent('input');
  await page.locator('[data-crop-edge="2"]').fill('800');await page.locator('[data-crop-edge="2"]').dispatchEvent('input');
  mkdirSync('deliverables/sales-queues',{recursive:true});
  await page.screenshot({path:'deliverables/sales-queues/document-crop.png'});
  await page.getByRole('button',{name:'Use crop',exact:true}).click();
  await page.waitForFunction(()=>!!cropSaved());
  const size=await page.evaluate(async()=>{const doc=cropSaved();const bitmap=await createImageBitmap(new Blob([Uint8Array.from(atob(doc.content),c=>c.charCodeAt(0))],{type:doc.mimeType}));return [bitmap.width,bitmap.height];});
  assert.deepEqual(size,[240,300]);
  await upload();await page.getByRole('button',{name:'Cancel',exact:true}).click();
  assert.deepEqual(await page.evaluate(()=>[cropSaved().fileName,cropSaved().mimeType]),['scan.png','image/png']);
  await page.setViewportSize({width:390,height:844});await page.evaluate(()=>testView('pendingDocuments'));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'deliverables/sales-queues/pending-documents-mobile.png',fullPage:true});
  await page.evaluate(()=>setIntakeLanguage('mr'));
  assert.equal(await page.locator('h1').innerText(),'प्रलंबित कागदपत्रे');
  assert.match(await page.locator('.case-table tbody').innerText(),/कागदपत्रे प्रलंबित/);
  assert.equal(await page.locator('.side [data-view="pendingPayment"] span').innerText(),'प्रलंबित देयक');
  await page.screenshot({path:'deliverables/sales-queues/pending-documents-marathi.png',fullPage:true});
  await page.evaluate(()=>testWorkflow('Assigned'));
  assert.match(await page.locator('#nextStatus').innerText(),/कागदपत्रे योग्य आहेत/);
  assert.match(await page.locator('#nextStatus').innerText(),/कागदपत्रे प्रलंबित/);
  await page.evaluate(()=>testWorkflow('Ready to Submit'));
  assert.match(await page.locator('#nextStatus').innerText(),/अर्ज सादर केला/);
  assert.match(await page.locator('#nextStatus').innerText(),/अर्ज पुन्हा सादर केला/);
  await page.evaluate(()=>testWorkflow('Application Resubmitted'));
  assert.match(await page.locator('#nextStatus').innerText(),/अर्ज नाकारला/);
  assert.match(await page.locator('#nextStatus').innerText(),/अर्ज पूर्ण झाला - कागदपत्र अपलोड करा/);
  await page.evaluate(()=>testForwarding());
  assert.equal(await page.locator('#submitReupload').innerText(),'पुढे पाठवण्यासाठी पुन्हा प्रयत्न करा');
  assert.match(await page.locator('.reupload-submission').innerText(),/अतिरिक्त देयक आवश्यक नाही/);
  await page.evaluate(()=>testCrop());
  await upload();
  await page.getByRole('heading',{name:'कागदपत्र क्रॉप करा',exact:true}).waitFor();
  assert.equal(await page.locator('[data-crop="save"]').innerText(),'क्रॉप केलेले चित्र वापरा');
  assert.equal(await page.locator('[data-crop="original"]').innerText(),'मूळ चित्र वापरा');
  assert.equal(await page.locator('[data-crop="cancel"]').innerText(),'रद्द करा');
  await page.screenshot({path:'deliverables/sales-queues/document-crop-marathi.png',fullPage:true});
  await page.locator('[data-crop="cancel"]').click();
  assert.deepEqual(errors,[]);
  console.log('Sales queues, column visibility, crop output dimensions, cancel, mobile layout, and Marathi queues/workflow/crop controls passed.');
} finally {await browser.close();}

